package ai.whisperio.android

import ai.whisperio.android.history.AppDatabase
import ai.whisperio.android.history.MIGRATION_1_2
import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.test.core.app.ApplicationProvider
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * CONTRACT-1.2 F3: Room 1 -> 2. Needs `schemas/ai.whisperio.android.history.AppDatabase/1.json` AND `2.json` as test
 * assets (build.gradle.kts adds the schemas dir to the test assets). 2.json is KSP output with an identity hash, so it
 * is generated by the batch gate (one build) and committed there; until then this test cannot validate version 2.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class RoomMigrationTest {
    @get:Rule val helper = MigrationTestHelper(InstrumentationRegistry.getInstrumentation(), AppDatabase::class.java)

    private val name = "migration-test.db"

    private val insertWidget =
        "INSERT INTO recording (id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted) " +
            "VALUES ('w1', 1000, 4200, 'DONE', 'openai', 'whisper-1', 'pl', 'z widgetu', NULL, '/data/w1.m4a', 'WIDGET', NULL)"

    private val insertKeyboard =
        "INSERT INTO recording (id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted) " +
            "VALUES ('k1', 2000, 1500, 'FAILED', 'groq', 'whisper-large-v3-turbo', 'auto', NULL, 'HTTP 401', NULL, 'KEYBOARD', 0)"

    @Test fun migrate1To2KeepsRowsAndAddsANullCategory() {
        helper.createDatabase(name, 1).apply {
            execSQL(insertWidget)
            execSQL(insertKeyboard)
            close()
        }

        val db = helper.runMigrationsAndValidate(name, 2, true, MIGRATION_1_2)
        db.query(
            "SELECT id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted, category " +
                "FROM recording ORDER BY created_at",
        ).use { c ->
            assertEquals(2, c.count)
            c.moveToFirst()
            assertEquals("w1", c.getString(0))
            assertEquals(1000L, c.getLong(1))
            assertEquals(4200L, c.getLong(2))
            assertEquals("DONE", c.getString(3))
            assertEquals("openai", c.getString(4))
            assertEquals("whisper-1", c.getString(5))
            assertEquals("pl", c.getString(6))
            assertEquals("z widgetu", c.getString(7))
            assertTrue(c.isNull(8))
            assertEquals("/data/w1.m4a", c.getString(9))
            assertEquals("WIDGET", c.getString(10))
            assertTrue(c.isNull(11))
            assertTrue(c.isNull(12)) // category: nullable, no default
            c.moveToNext()
            assertEquals("k1", c.getString(0))
            assertEquals("HTTP 401", c.getString(8))
            assertEquals(0, c.getInt(11))
            assertTrue(c.isNull(12))
        }
    }

    @Test fun migratedDatabaseOpensWithRoomAndAcceptsACategory() = runBlocking {
        helper.createDatabase(name, 1).apply {
            execSQL(insertWidget)
            close()
        }
        helper.runMigrationsAndValidate(name, 2, true, MIGRATION_1_2).close()

        val room = Room.databaseBuilder(ApplicationProvider.getApplicationContext(), AppDatabase::class.java, name)
            .addMigrations(MIGRATION_1_2).build()
        try {
            val dao = room.recordings()
            assertNull(dao.get("w1")!!.category)
            dao.setCategory("w1", "work")
            assertEquals("work", dao.get("w1")!!.category)
            assertEquals("z widgetu", dao.get("w1")!!.transcript)
        } finally {
            room.close()
        }
    }
}
