package ai.whisperio.android

import ai.whisperio.android.history.AppDatabase
import ai.whisperio.android.history.MIGRATION_1_2
import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.sqlite.SQLiteConnection
import androidx.sqlite.driver.AndroidSQLiteDriver
import androidx.sqlite.execSQL
import androidx.test.core.app.ApplicationProvider
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * CONTRACT-1.2 F3: Room 1 -> 2. Needs `schemas/ai.whisperio.android.history.AppDatabase/1.json` AND `2.json` as assets
 * (build.gradle.kts adds the schemas dir to the debug assets, the ones Robolectric sees). 2.json is KSP output with an
 * identity hash, so it is generated by the batch gate (one build) and committed there.
 *
 * Uses the driver-based helper (AndroidSQLiteDriver on an explicit file): the SupportSQLite helper's driver matches
 * the requested path with substringAfterLast('/'), which never matches on a Windows host (Robolectric, '\' paths).
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class RoomMigrationTest {
    private val dbFile: File =
        ApplicationProvider.getApplicationContext<android.content.Context>().getDatabasePath("migration-test.db")

    @get:Rule val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        dbFile,
        AndroidSQLiteDriver(),
        AppDatabase::class,
    )

    private val insertWidget =
        "INSERT INTO recording (id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted) " +
            "VALUES ('w1', 1000, 4200, 'DONE', 'openai', 'whisper-1', 'pl', 'z widgetu', NULL, '/data/w1.m4a', 'WIDGET', NULL)"

    private val insertKeyboard =
        "INSERT INTO recording (id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted) " +
            "VALUES ('k1', 2000, 1500, 'FAILED', 'groq', 'whisper-large-v3-turbo', 'auto', NULL, 'HTTP 401', NULL, 'KEYBOARD', 0)"

    private fun SQLiteConnection.count(): Long = prepare("SELECT COUNT(*) FROM recording").use { it.step(); it.getLong(0) }

    @Test fun migrate1To2KeepsRowsAndAddsANullCategory() {
        helper.createDatabase(1).apply {
            execSQL(insertWidget)
            execSQL(insertKeyboard)
            close()
        }

        val db = helper.runMigrationsAndValidate(2, listOf(MIGRATION_1_2))
        try {
            assertEquals(2L, db.count())
            db.prepare(
                "SELECT id, created_at, duration_ms, status, provider, model, language, transcript, error, audio_path, source, inserted, category " +
                    "FROM recording ORDER BY created_at",
            ).use { c ->
                assertTrue(c.step())
                assertEquals("w1", c.getText(0))
                assertEquals(1000L, c.getLong(1))
                assertEquals(4200L, c.getLong(2))
                assertEquals("DONE", c.getText(3))
                assertEquals("openai", c.getText(4))
                assertEquals("whisper-1", c.getText(5))
                assertEquals("pl", c.getText(6))
                assertEquals("z widgetu", c.getText(7))
                assertTrue(c.isNull(8))
                assertEquals("/data/w1.m4a", c.getText(9))
                assertEquals("WIDGET", c.getText(10))
                assertTrue(c.isNull(11))
                assertTrue(c.isNull(12)) // category: nullable, no default
                assertTrue(c.step())
                assertEquals("k1", c.getText(0))
                assertEquals("HTTP 401", c.getText(8))
                assertEquals(0, c.getInt(11))
                assertTrue(c.isNull(12))
            }
        } finally {
            db.close()
        }
    }

    @Test fun migratedDatabaseOpensWithRoomAndAcceptsACategory() = runBlocking {
        helper.createDatabase(1).apply {
            execSQL(insertWidget)
            close()
        }
        helper.runMigrationsAndValidate(2, listOf(MIGRATION_1_2)).close()

        // Same builder shape as production (no driver set); the absolute path names the file the helper migrated.
        val room = Room.databaseBuilder(ApplicationProvider.getApplicationContext(), AppDatabase::class.java, dbFile.path)
            .addMigrations(MIGRATION_1_2).build()
        try {
            val dao = room.recordings()
            assertNull(dao.get("w1")!!.category)
            dao.setCategory("w1", "work")
            assertEquals("work", dao.get("w1")!!.category)
            assertEquals("z widgetu", dao.get("w1")!!.transcript)
        } finally {
            room.close()
        }
    }
}
